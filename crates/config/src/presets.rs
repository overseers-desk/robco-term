//! Built-in screen and chassis presets, in their list order. Each preset's
//! shape is exactly what the persisted screen/chassis object produces, so
//! each one maps directly onto [`crate::ScreenSettings`] /
//! [`crate::ChassisSettings`].
//!
//! A screen preset states only what it changes from the default screen
//! ("Default Amber", `ScreenSettings::default()`): moving a value in the
//! default moves it in every preset that does not restate it, deliberately.
//! A field a preset means to pin regardless of the default must be stated
//! in the preset.
//!
//! The built-in list also carries a `builtin: true` flag and, for chassis, a
//! `description` string. Neither is part of the persisted screen/chassis
//! object; they are UI-list metadata, so they are not reproduced here.

