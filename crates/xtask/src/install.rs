//! `xtask install`, `xtask dist` and `xtask stage-deb`: getting the Linux
//! build off the build machine and onto a user's.
//!
//! All three lay out the same three files. `install` writes them into a prefix
//! the caller names, `dist` writes them into a staging directory and rolls it
//! into a versioned `tar.gz`, and `stage-deb` writes them under the staging
//! root `debian/rules` hands it, where debhelper takes over (strip,
//! `${shlibs:Depends}`, the doc files) and `dpkg-buildpackage` writes the
//! `.deb` into the parent directory. One
//! [`lay_out`] means the three can never disagree about what an installation
//! is.
//!
//! # What is embedded and what is installed
//!
//! **Installed**: the entire on-disk footprint, three files plus one more
//! when a settings binary is supplied:
//!
//! | Path under the prefix | What it is |
//! |---|---|
//! | `bin/robco-term` | the binary |
//! | `share/applications/robco-term.desktop` | the desktop entry, `packaging/robco-term.desktop` verbatim |
//! | `share/icons/hicolor/256x256/apps/robco-term.png` | the icon, `packaging/icons/robco-term.png` verbatim |
//! | `bin/robco-settings` | the settings window, in the shape its route ships (below) |
//!
//! `robco-settings` is not built by this workspace's own `cargo build`: it
//! is a Tcl/Tk application, and it ships in the shape its destination
//! expects. The tarball carries the single-file image
//! `settings/zipfs/build-selfcontained.sh` builds (`--settings-binary`
//! names it), because a tarball promises to run on a host with nothing
//! installed; `dist` refuses to produce one without it, and `install`
//! accepts running without one (a developer install, GUI-less). The `.deb`
//! instead ships the Tcl sources under `share/robco-term/settings`, the
//! launcher at `bin/robco-settings` with its ROOT pointed there, and
//! `tcl9.0`/`tk9.0` in its `Depends` (declared in `debian/control`): on
//! Debian the interpreter is the distribution's to provide, the same rule
//! `dh_shlibdeps` applies to the C libraries.
//!
//! **Embedded**: compiled into the binary, so none of it is installed, none
//! of it is looked up at run time, and the binary does not care where it sits
//! or whether a source checkout exists:
//!
//! - the 24 bundled font faces (`include_bytes!` in `robco-term`'s
//!   `fonts::bundled`),
//! - every shader source: the CRT chain's passes (`robco-crt-render`'s
//!   `preset`), the burn-in pass (`crt::burn_in`), the chassis metal, LED
//!   matrix and tape-label passes (`robco-chassis`'s `shaders`), and the
//!   grid's WGSL (`robco-term`'s `render`),
//! - the CRT chain's noise texture (`allNoise512.png`),
//! - the 14 screen and 3 chassis presets, which are Rust data in
//!   `robco-config`'s `presets`, not files.
//!
//! The chain's `.slangp` preset *is* written to a file at run time, but into
//! the user's cache directory (the `preset/robco.slangp` the startup log
//! names), from the embedded sources. It is a cache, not an installed asset:
//! deleting it costs one regeneration.
//!
//! **Neither**: created under the user's own directories on first run, and
//! no business of a package: `robco-term/config.toml` under the XDG config
//! directory, the crash log, and the instance lock and socket in
//! `XDG_RUNTIME_DIR`.
//!
//! The practical consequence, and the reason [`lay_out`] is this short: the
//! installation is relocatable. `bin/robco-term` copied anywhere runs, which
//! is what makes a plain tarball a legitimate release format here rather than
//! a shortcut.
//!
//! # The placeholder icon
//!
//! `packaging/icons/robco-term.png` is a placeholder, not branding. The app
//! has no real icon yet, so this one is plain geometry drawn from
//! nothing: an amber rounded frame around a block cursor and two bars, on the
//! near-black the screen presets use. It was generated by, and can be
//! regenerated by:
//!
//! ```text
//! convert -size 256x256 xc:'#0d0b06' \
//!   -fill none -stroke '#ffb000' -strokewidth 10 \
//!   -draw 'roundrectangle 20,20 235,235 28,28' \
//!   -fill '#ffb000' -stroke none \
//!   -draw 'rectangle 62,96 86,132' \
//!   -draw 'rectangle 62,150 170,160' \
//!   -draw 'rectangle 100,96 194,106' \
//!   png32:packaging/icons/robco-term.png
//! ```
//!
//! Real branding drops in by replacing that one file at that one path, with no
//! code change: the name it installs under is the binary's basename, which is
//! the application's identity and what the desktop entry's `Icon=` names.
//! Additional sizes, when there is art worth rendering at them, go in beside
//! it and get another line in [`ICONS`].

use anyhow::{bail, Context, Result};
use std::path::{Path, PathBuf};
use std::process::Command;

/// The desktop entry and the icon travel inside this binary rather than being
/// read out of a checkout, for the same reason the app's own assets do: an
/// `xtask` that has to find its source tree to install is an `xtask` that
/// installs something different depending on where it is run from.
const DESKTOP_ENTRY: &str = include_str!("../../../packaging/robco-term.desktop");

/// The icons to install, as (nominal size, bytes). One entry today; the
/// placeholder's own note says what adding more looks like.
const ICONS: &[(u32, &[u8])] = &[(
    256,
    include_bytes!("../../../packaging/icons/robco-term.png"),
)];

/// The workspace manifest, parsed at run time for the product's version.
/// `include_str!` rather than a path lookup so the number travels with the
/// binary, and so cargo rebuilds `xtask` when the version changes.
const WORKSPACE_MANIFEST: &str = include_str!("../../../Cargo.toml");

/// The application's identity: the binary's basename, which is also the
/// desktop entry's basename, the icon's basename, the WM_CLASS the window
/// presents and the Debian package's name. One string, per `app::identity`.
pub const NAME: &str = "robco-term";

/// The settings window's basename, installed as `bin/robco-settings`
/// alongside `bin/robco-term` when a `--settings-binary` is supplied. It is
/// the launcher name the Tcl/Tk app carries (`settings/robco-settings`), and
/// the name `settings/zipfs/build-selfcontained.sh`'s image reports for
/// `--version`.
pub const SETTINGS_NAME: &str = "robco-settings";

/// The product's version, from `[workspace.package]` in the workspace
/// manifest. Read, never written: bumping it is a release decision that
/// happens in the manifest, and packaging only ever stamps what it finds.
pub fn version() -> Result<String> {
    let doc: toml_edit::DocumentMut = WORKSPACE_MANIFEST
        .parse()
        .context("parsing the workspace Cargo.toml")?;
    doc.get("workspace")
        .and_then(|w| w.get("package"))
        .and_then(|p| p.get("version"))
        .and_then(|v| v.as_str())
        .map(str::to_string)
        .context("no [workspace.package] version in the workspace Cargo.toml")
}

/// `<name>-<version>-linux-<arch>`, the stem a release artifact is known by.
/// The architecture is this build's, since `robco-term` drags a C++
/// dependency (simdutf, through the terminal core) and so is built natively
/// per platform rather than cross-compiled: the artifact name has to say
/// which machine it came off.
fn artifact_stem(version: &str) -> String {
    format!("{NAME}-{version}-linux-{}", std::env::consts::ARCH)
}

/// Writes the installation under `root`, which plays the part of
/// `<destdir><prefix>`. Answers the installed paths, in the order written.
///
/// This is the whole definition of "an installation": one executable and two
/// XDG data files, plus `bin/robco-settings` when `settings_binary` is given.
/// Everything else `robco-term` needs is inside its executable (see the
/// module doc); `robco-settings` is a separate Tcl/Tk image and is only
/// copied into place, never built here.
fn lay_out(root: &Path, binary: &Path, settings_binary: Option<&Path>) -> Result<Vec<PathBuf>> {
    let mut written = Vec::new();

    let bin_dir = root.join("bin");
    std::fs::create_dir_all(&bin_dir).with_context(|| format!("creating {}", bin_dir.display()))?;
    let installed_binary = bin_dir.join(NAME);
    // Remove first: copying onto a running executable is ETXTBSY, and
    // re-installing over a live install is the normal case.
    let _ = std::fs::remove_file(&installed_binary);
    std::fs::copy(binary, &installed_binary).with_context(|| {
        format!(
            "copying {} to {}",
            binary.display(),
            installed_binary.display()
        )
    })?;
    set_mode(&installed_binary, 0o755)?;
    written.push(installed_binary);

    let applications = root.join("share/applications");
    std::fs::create_dir_all(&applications)
        .with_context(|| format!("creating {}", applications.display()))?;
    let entry = applications.join(format!("{NAME}.desktop"));
    std::fs::write(&entry, DESKTOP_ENTRY)
        .with_context(|| format!("writing {}", entry.display()))?;
    set_mode(&entry, 0o644)?;
    written.push(entry);

    for (size, bytes) in ICONS {
        let dir = root.join(format!("share/icons/hicolor/{size}x{size}/apps"));
        std::fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
        let icon = dir.join(format!("{NAME}.png"));
        std::fs::write(&icon, bytes).with_context(|| format!("writing {}", icon.display()))?;
        set_mode(&icon, 0o644)?;
        written.push(icon);
    }

    if let Some(settings_binary) = settings_binary {
        let installed_settings = bin_dir.join(SETTINGS_NAME);
        // Same ETXTBSY reasoning as the main binary above.
        let _ = std::fs::remove_file(&installed_settings);
        std::fs::copy(settings_binary, &installed_settings).with_context(|| {
            format!(
                "copying {} to {}",
                settings_binary.display(),
                installed_settings.display()
            )
        })?;
        set_mode(&installed_settings, 0o755)?;
        written.push(installed_settings);
    }

    Ok(written)
}

/// The `.deb`'s shape of the settings window: the Tcl sources under
/// `share/robco-term/settings` and the launcher at `bin/robco-settings`
/// with its ROOT pointed there, leaning on the distribution's own
/// `tcl9.0`/`tk9.0` (declared in `Depends` by [`deb`]) instead of
/// bundling an interpreter.
fn lay_out_settings_scripts(root: &Path) -> Result<Vec<PathBuf>> {
    let mut written = Vec::new();
    let source = workspace_root().join("settings");
    let share = root.join("share").join(NAME).join("settings");

    for dir in ["lib", "ui"] {
        let dest = share.join(dir);
        std::fs::create_dir_all(&dest).with_context(|| format!("creating {}", dest.display()))?;
        let from = source.join(dir);
        for entry in
            std::fs::read_dir(&from).with_context(|| format!("reading {}", from.display()))?
        {
            let path = entry?.path();
            // Every regular file in these two directories, whatever it is
            // named. They hold the settings program's runtime and nothing
            // else, and a copy that names the extensions it knows ships a
            // launcher that cannot start the day one arrives it has not
            // heard of: `lib/tomledit-1.0.tm` was left out of 0.1.4 that
            // way, and the installed launcher died on the line that sources
            // it.
            if !path.is_file() {
                continue;
            }
            let target = dest.join(path.file_name().expect("a read_dir entry has a name"));
            std::fs::copy(&path, &target).with_context(|| {
                format!("copying {} to {}", path.display(), target.display())
            })?;
            set_mode(&target, 0o644)?;
            written.push(target);
        }
    }

    let launcher_source = source.join(SETTINGS_NAME);
    let launcher = std::fs::read_to_string(&launcher_source)
        .with_context(|| format!("reading {}", launcher_source.display()))?;
    let patched = point_root_at(&launcher, &format!("/usr/share/{NAME}/settings"))?;
    let bin_dir = root.join("bin");
    std::fs::create_dir_all(&bin_dir).with_context(|| format!("creating {}", bin_dir.display()))?;
    let installed_launcher = bin_dir.join(SETTINGS_NAME);
    std::fs::write(&installed_launcher, patched)
        .with_context(|| format!("writing {}", installed_launcher.display()))?;
    set_mode(&installed_launcher, 0o755)?;
    written.push(installed_launcher);

    Ok(written)
}

/// Rewrite the launcher's `set ROOT ...` line to the installed location.
/// The launcher derives ROOT from its own path when run from a checkout;
/// installed to `bin/` away from its sources, it has to be told. Refuses a
/// launcher with no such line rather than installing one that resolves
/// nothing.
fn point_root_at(launcher: &str, root: &str) -> Result<String> {
    if !launcher.lines().any(|l| l.starts_with("set ROOT ")) {
        bail!("the {SETTINGS_NAME} launcher has no `set ROOT` line to point at {root}");
    }
    let lines: Vec<String> = launcher
        .lines()
        .map(|line| {
            if line.starts_with("set ROOT ") {
                format!("set ROOT {root}")
            } else {
                line.to_string()
            }
        })
        .collect();
    Ok(lines.join("\n") + "\n")
}

fn set_mode(path: &Path, mode: u32) -> Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode))
            .with_context(|| format!("chmod {mode:o} {}", path.display()))?;
    }
    #[cfg(not(unix))]
    let _ = (path, mode);
    Ok(())
}

/// The binary to package: the one the caller named, or a fresh release build.
///
/// Building here rather than making the caller do it is what lets `cargo run
/// -p xtask -- install --prefix <dir>` be the whole instruction. `--binary`
/// exists so a release pipeline can package an artifact it built (and checked)
/// earlier instead of rebuilding it.
fn resolve_binary(binary: Option<PathBuf>) -> Result<PathBuf> {
    if let Some(path) = binary {
        return std::fs::canonicalize(&path)
            .with_context(|| format!("binary not found: {}", path.display()));
    }

    eprintln!("building the release binary (`cargo build --release -p robco-app`)");
    // From the workspace root, not the caller's directory: `xtask install` is
    // runnable from anywhere (everything it installs is inside it), and a
    // `cargo build` inherited from some other directory would either fail or,
    // worse, build some other workspace.
    //
    // `--message-format=json-render-diagnostics` is how the built path is
    // *asked for* rather than guessed. Where cargo puts a target directory has
    // at least four sources: `--target-dir`, `CARGO_TARGET_DIR`,
    // `build.target-dir` in any of the layered config files, and the default
    // beside the workspace manifest. Reproducing that precedence here
    // means being wrong the first time someone's config disagrees. This was not
    // hypothetical: the first version of this function assumed
    // `CARGO_TARGET_DIR` or `<workspace>/target` and failed on a host where
    // neither held. Diagnostics still render to stderr, so the build looks the
    // same to whoever is watching it.
    let output = Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
        .args([
            "build",
            "--release",
            "-p",
            "robco-app",
            "--message-format=json-render-diagnostics",
        ])
        .current_dir(workspace_root())
        .stderr(std::process::Stdio::inherit())
        .output()
        .context("spawning cargo")?;
    if !output.status.success() {
        bail!(
            "`cargo build --release -p robco-app` exited with {}",
            output.status
        );
    }

    let built = executable_from_cargo_messages(&String::from_utf8_lossy(&output.stdout))
        .context("cargo reported no executable artifact for robco-app")?;
    std::fs::canonicalize(&built)
        .with_context(|| format!("release build did not produce {}", built.display()))
}

/// The executable path out of cargo's JSON message stream.
///
/// A full JSON parse would buy nothing here: the field is a plain string in a
/// machine-written line, and `robco-app` produces exactly one executable, so
/// the last `"executable"` that is not `null` is it. Kept as its own function
/// so it can be tested on a recorded line rather than only against a real
/// build.
fn executable_from_cargo_messages(stdout: &str) -> Option<PathBuf> {
    const KEY: &str = "\"executable\":\"";
    stdout
        .lines()
        .filter_map(|line| {
            let start = line.find(KEY)? + KEY.len();
            let rest = &line[start..];
            let end = rest.find('"')?;
            Some(PathBuf::from(&rest[..end]))
        })
        .next_back()
}

/// The workspace root, resolved from this crate's compile-time location the
/// same way [`crate::snap`] resolves its own repo-relative lookups.
fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .map(Path::to_path_buf)
        .unwrap_or_else(|| PathBuf::from("."))
}

/// `HEAD`'s own commit timestamp (seconds since the epoch), read from git
/// rather than the wall clock.
///
/// `xtask dist` stamps this onto every entry it archives (see [`dist`]), so
/// that two runs at the same commit -- the reproducibility a release
/// pipeline or a third party rebuilding the same tag wants to be able to
/// check -- produce byte-identical tarballs. Reading it from the system
/// clock instead would make every run's archive different from every other,
/// which is what a plain `tar` invocation over a freshly-staged directory
/// already does by accident: each file's mtime is "when `dist` happened to
/// stage it", not anything about the release.
fn released_commit_timestamp() -> Result<i64> {
    let output = Command::new("git")
        .arg("-C")
        .arg(workspace_root())
        .args(["log", "-1", "--format=%ct", "HEAD"])
        .output()
        .context("spawning git to read HEAD's commit timestamp")?;
    if !output.status.success() {
        bail!(
            "git log -1 --format=%ct HEAD exited with {}: {}",
            output.status,
            String::from_utf8_lossy(&output.stderr)
        );
    }
    String::from_utf8_lossy(&output.stdout)
        .trim()
        .parse::<i64>()
        .context("git log -1 --format=%ct HEAD did not print a Unix timestamp")
}

/// Runs the *installed* copy with a scrubbed environment and checks it reports
/// the version being packaged.
///
/// Two things at once, both cheap. It proves the installed file is executable
/// and starts with no source checkout, no user config and no `HOME` it has
/// ever seen: the property the whole embedded-assets design is claiming. And
/// it catches a `--binary` that is not this tree's build, which is the one way
/// a tarball can end up named for a version it does not contain.
///
/// It deliberately does not open a window: that needs a display and belongs to
/// `xtask snap`, which already does it.
fn check_installed(installed: &Path, version: &str) -> Result<()> {
    let home = tempfile::Builder::new()
        .prefix("robco-install-check.")
        .tempdir()
        .context("creating a scratch HOME for the install check")?;

    let mut command = Command::new(installed);
    command
        .arg("--version")
        .env_clear()
        // PATH so the loader's helpers resolve; nothing else is inherited, so
        // there is no XDG variable, no CARGO_*, and no pointer to a checkout.
        .env("PATH", "/usr/bin:/bin")
        .env("HOME", home.path());
    let output = command
        .output()
        .with_context(|| format!("running {} --version", installed.display()))?;

    let reported = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if !output.status.success() {
        bail!(
            "{} --version exited with {} in a clean environment",
            installed.display(),
            output.status
        );
    }
    let expected = format!("{NAME} {version}");
    if reported != expected {
        bail!("installed binary reports {reported:?}, expected {expected:?}");
    }
    println!("  checked: {reported} runs from the prefix with a clean HOME");
    Ok(())
}

pub struct InstallArgs {
    pub prefix: PathBuf,
    pub destdir: Option<PathBuf>,
    pub binary: Option<PathBuf>,
    pub settings_binary: Option<PathBuf>,
}

pub fn install(args: InstallArgs) -> Result<()> {
    let version = version()?;
    let binary = resolve_binary(args.binary)?;
    let root = staged_root(&args.prefix, args.destdir.as_deref());

    if args.settings_binary.is_none() {
        println!(
            "note: no --settings-binary given; installing {NAME} without {SETTINGS_NAME} (the settings window). Build one with settings/zipfs/build-selfcontained.sh and re-run with --settings-binary <path> to include it."
        );
    }

    let written = lay_out(&root, &binary, args.settings_binary.as_deref())?;
    println!("installed {} {version} to {}", NAME, root.display());
    for path in &written {
        println!("  {}", path.display());
    }

    check_installed(&root.join("bin").join(NAME), &version)?;

    // The desktop entry's `Exec=` is a bare name, so a prefix outside PATH
    // installs an entry that cannot launch anything. Saying so beats writing
    // an absolute path that a later move would silently break.
    let bin_dir = root.join("bin");
    let on_path = std::env::var_os("PATH")
        .map(|path| std::env::split_paths(&path).any(|dir| dir == bin_dir))
        .unwrap_or(false);
    if !on_path {
        println!(
            "note: {} is not on PATH, so the desktop entry's `Exec=robco-term` will not resolve\n      until it is (the entry names the binary rather than one prefix on purpose).",
            bin_dir.display()
        );
    }

    Ok(())
}

/// `<destdir><prefix>`, the GNU staging idiom: with no destdir the prefix is
/// the root, and with one the prefix is re-rooted under it.
fn staged_root(prefix: &Path, destdir: Option<&Path>) -> PathBuf {
    match destdir {
        None => prefix.to_path_buf(),
        Some(dest) => dest.join(prefix.strip_prefix("/").unwrap_or(prefix)),
    }
}

pub struct DistArgs {
    pub out_dir: PathBuf,
    pub binary: Option<PathBuf>,
    pub settings_binary: Option<PathBuf>,
}

/// `xtask dist`: the install layout, rolled into a versioned `tar.gz`.
///
/// The tarball's single top-level directory is the artifact stem, so it
/// unpacks into one named directory rather than over the current one, and its
/// contents are exactly what `install` writes: relocatable, because the
/// module doc's embedded/installed split leaves nothing to relocate.
///
/// `--settings-binary` is required here, not optional as it is for `install`:
/// this is what a user downloads, and an official package with no settings
/// window is a bug, not a smaller install.
/// Takes the debug information out of the staged binary, leaving the tarball
/// carrying what the program is made of and nothing else.
///
/// This is the other package routes' behaviour written down for the one route
/// that lacked it: `dh_strip` does it for the deb, and the Windows and macOS
/// artifacts never carried debug information at all. The developer's own
/// `target/release` copy keeps the line tables the release profile asks for;
/// what ships does not.
///
/// `-S` is the strip-debug flag on both GNU binutils and macOS. A failure here
/// stops the build rather than shipping the unstripped copy, because a tarball
/// that quietly carries a few hundred megabytes of DWARF is the thing this
/// exists to prevent.
fn strip_debug(binary: &Path) -> Result<()> {
    let status = std::process::Command::new("strip")
        .arg("-S")
        .arg(binary)
        .status()
        .with_context(|| format!("running strip on {}", binary.display()))?;
    if !status.success() {
        bail!("strip on {} exited with {status}", binary.display());
    }
    Ok(())
}

pub fn dist(args: DistArgs) -> Result<()> {
    let Some(settings_binary) = args.settings_binary else {
        bail!(
            "official {NAME} packages always carry {SETTINGS_NAME}; pass --settings-binary <path>. Build one with settings/zipfs/build-selfcontained.sh."
        );
    };

    let version = version()?;
    let mtime = released_commit_timestamp()?;
    let binary = resolve_binary(args.binary)?;
    let stem = artifact_stem(&version);

    let staging = tempfile::Builder::new()
        .prefix("robco-dist.")
        .tempdir()
        .context("creating the dist staging directory")?;
    let root = staging.path().join(&stem);
    lay_out(&root, &binary, Some(&settings_binary))?;
    strip_debug(&root.join("bin").join(NAME))?;
    check_installed(&root.join("bin").join(NAME), &version)?;

    let tarball = archive(staging.path(), &stem, &args.out_dir, mtime)?;

    let bytes = std::fs::metadata(&tarball).map(|m| m.len()).unwrap_or(0);
    println!(
        "wrote {} ({:.1} MiB)",
        tarball.display(),
        bytes as f64 / (1024.0 * 1024.0)
    );
    Ok(())
}

/// Rolls `staging/<stem>` into `<out_dir>/<stem>.tar.gz`. Split out of
/// [`dist`] so the archiving step -- the part reproducibility is actually a
/// claim about -- is callable from a test without a real binary to package
/// or a `check_installed` run to satisfy.
///
/// `--sort=name`, a fixed owner and `--mtime` keep the archive from carrying
/// this machine's uid, readdir order or the moment this happened to run into
/// a release artifact: two runs at the same `mtime` produce the same bytes
/// (`dist` sources it from [`released_commit_timestamp`], not the clock).
/// GNU tar's own flags rather than a Rust tar crate, for the reason `proc`
/// already states: the battle-tested tool is the better trade.
fn archive(staging: &Path, stem: &str, out_dir: &Path, mtime: i64) -> Result<PathBuf> {
    std::fs::create_dir_all(out_dir).with_context(|| format!("creating {}", out_dir.display()))?;
    let out_dir = std::fs::canonicalize(out_dir)
        .with_context(|| format!("resolving {}", out_dir.display()))?;
    let tarball = out_dir.join(format!("{stem}.tar.gz"));

    let status = Command::new("tar")
        .arg("--create")
        .arg("--gzip")
        .arg("--sort=name")
        .arg("--owner=0")
        .arg("--group=0")
        .arg("--numeric-owner")
        .arg(format!("--mtime=@{mtime}"))
        .arg("--file")
        .arg(&tarball)
        .arg("--directory")
        .arg(staging)
        .arg(stem)
        .status()
        .context("spawning tar")?;
    if !status.success() {
        bail!("tar exited with {status}");
    }
    Ok(tarball)
}

pub struct StageDebArgs {
    pub root: PathBuf,
    pub binary: Option<PathBuf>,
}

/// `xtask stage-deb`: the install layout plus the settings sources, into
/// the staging root `debian/rules` names. Everything Debian-specific past
/// the layout (strip, `${shlibs:Depends}`, the changelog and copyright
/// installation, modes and ownership) is
/// debhelper's, which is the point of packaging with it.
pub fn stage_deb(args: StageDebArgs) -> Result<()> {
    let version = version()?;
    let binary = resolve_binary(args.binary)?;
    let mut written = lay_out(&args.root, &binary, None)?;
    written.extend(lay_out_settings_scripts(&args.root)?);
    check_installed(&args.root.join("bin").join(NAME), &version)?;
    for path in written {
        println!("staged {}", path.display());
    }
    Ok(())
}

#[cfg(test)]
